"""Интерфейсы между зонами. Владелец: участник 1."""
from __future__ import annotations

from typing import Protocol

from .models import Chunk, Edge, Hit, Node


class VectorIndexLike(Protocol):           # реализует участник 2
    def add(self, chunks: list[Chunk]) -> None: ...
    def search(self, query: str, k: int) -> list[Hit]: ...
    def delete_by_path(self, path: str) -> None: ...


class LexicalLike(Protocol):               # реализует участник 2
    def search(self, query: str, k: int) -> list[Hit]: ...


class GraphStoreLike(Protocol):            # реализует участник 3
    def add_nodes(self, nodes: list[Node]) -> None: ...
    def add_edges(self, edges: list[Edge]) -> None: ...
    def save(self) -> None: ...
    def load(self) -> None: ...
    def callers(self, symbol: str, depth: int = 1) -> list[str]: ...
    def callees(self, symbol: str, depth: int = 1) -> list[str]: ...
    def expand(self, seed_ids: list[str], seed_scores: dict[str, float],
               hops: int = 2) -> list[tuple[str, float, str]]: ...


class ToolClientLike(Protocol):            # реализует участник 4 (с участником 1)
    def start(self) -> None: ...
    def list_tools_for_ollama(self) -> list[dict]: ...
    def call_tool(self, name: str, args: dict) -> str: ...
    def close(self) -> None: ...
